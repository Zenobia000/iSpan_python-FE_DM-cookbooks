"""Render committed host skills from canonical workflow templates."""

import argparse
from pathlib import Path
import sys

if __package__:
    from .ds_harness import SKILLS
else:
    from ds_harness import SKILLS

ROOT = Path(__file__).resolve().parents[1]
HOSTS = {"claude": (".claude/skills", "/"), "codex": (".agents/skills", "$")}


def render(host, root=ROOT):
    prefix = HOSTS[host][1]
    preamble = (
        f"從 repository 根目錄執行；目前 host 為 `{host}`。先讀 `skills/_shared/session.md`。\n"
        "已有 case 時先執行 `python3 tools/ds_harness.py status --case <case>`；"
        "沒有 case 時依任務目標 init。\n"
        f"本 host 的技能名稱示例：`{prefix}ds-frame`。記錄證據前先 start 取得此技能的 session。"
    )
    results = {}
    for skill in SKILLS:
        source = root / "skills" / skill / "SKILL.md.tmpl"
        text = source.read_text(encoding="utf-8")
        text = text.replace("{{SESSION_START}}", preamble).replace("{{INVOKE}}", prefix)
        if "{{" in text or "}}" in text:
            raise ValueError(f"未解析的模板欄位：{source}")
        if not text.startswith(f"---\nname: {skill}\n"):
            raise ValueError(f"模板名稱與 registry 不符：{source}")
        header, body = text.split("\n---\n", 1)
        results[Path(HOSTS[host][0]) / skill / "SKILL.md"] = (
            header + "\n---\n\n<!-- Generated by tools/render_skills.py; edit skills/ templates. -->\n" + body.lstrip("\n")
        )
    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--host", choices=(*HOSTS, "all"), default="all")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="read-only drift check")
    mode.add_argument("--write", action="store_true", help="render only registry-owned skill paths")
    parser.add_argument("--output-root", type=Path, default=ROOT)
    args = parser.parse_args()
    failed = []
    for host in HOSTS if args.host == "all" else [args.host]:
        for relative, text in render(host).items():
            target = args.output_root / relative
            if args.check:
                if not target.is_file() or target.read_text(encoding="utf-8") != text:
                    failed.append(str(relative))
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(text, encoding="utf-8")
    if failed:
        print("Skills missing or stale; run python3 tools/render_skills.py --write:\n" + "\n".join(failed), file=sys.stderr)
        return 1
    print("Skills current" if args.check else "Skills rendered")
    return 0


if __name__ == "__main__":
    sys.exit(main())
