"""Render portable skills and OpenCode command adapters from canonical sources."""

import argparse
from pathlib import Path
import re
import sys
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
HOSTS = {
    'claude': ('.claude/skills', '/'),
    'codex': ('.agents/skills', ''),
    'opencode': ('.agents/skills', ''),
}
SOURCE_URL = 'https://github.com/Zenobia000/iSpan_python-FE_DM-cookbooks/blob/feat/agentic-decision-analysis/'
LINK = re.compile(r'(?<!!)\[[^\]]*\]\(([^\s)]+)\)')


def version():
    return (ROOT / 'VERSION').read_text(encoding='utf-8').strip()


def command_text(skill, header):
    description = next(line for line in header.splitlines() if line.startswith('description:'))
    return (
        f'---\n{description}\n---\n\n'
        '<!-- Generated by tools/render_skills.py; edit skills/ templates. -->\n\n'
        f'先以原生 skill 工具載入 `{skill}`（`skill({{ name: "{skill}" }})`），'
        '再依載入的工作規約處理需求。沿用目前專案的研究文件與既有證據。\n\n'
        '使用者需求：\n\n$ARGUMENTS\n'
    )


def resources_for(skill, root):
    if skill == 'ds-init':
        return []
    selected = set((root / 'skills/_shared').rglob('*.md'))
    for folder in ('references', 'templates'):
        selected.update((root / 'skills' / skill / folder).rglob('*.md'))
    if skill == 'ds-review':
        selected.update((root / 'skills/ds-eda/references').glob('*.md'))
    # Keep Markdown links among method resources intact without depending on siblings.
    pending = list(selected)
    while pending:
        source = pending.pop()
        for target in LINK.findall(source.read_text(encoding='utf-8')):
            if '://' in target or target.startswith('#'):
                continue
            path = (source.parent / target.split('#')[0]).resolve()
            if root / 'skills' in path.parents and path.is_file() and path.suffix == '.md':
                if path not in selected:
                    selected.add(path)
                    pending.append(path)
    return sorted(selected)


def portable_text(text, source, root):
    def link(match):
        target = match.group(1)
        if '://' in target or target.startswith('#'):
            return match.group(0)
        path_text, marker, fragment = target.partition('#')
        path = (source.parent / path_text).resolve()
        if root / 'skills' in path.parents:
            return match.group(0)
        try:
            relative = path.relative_to(root)
        except ValueError:
            raise ValueError(f'參考路徑離開開發倉庫：{source}: {target}')
        url = SOURCE_URL + quote(relative.as_posix()) + (marker + fragment if marker else '')
        return match.group(0).replace('(' + target + ')', '(' + url + ')')
    text = LINK.sub(link, text)
    return re.sub(r'(?<![\w./-])skills/', 'resources/skills/', text)


def render(host, root=ROOT):
    root = Path(root).resolve()
    sources = sorted((root / 'skills').glob('*/SKILL.md.tmpl'))
    if not sources:
        raise ValueError('找不到技能模板。')
    definitions = {}
    for source in sources:
        skill = source.parent.name
        text = source.read_text(encoding='utf-8')
        if not text.startswith(f'---\nname: {skill}\n'):
            raise ValueError(f'模板名稱與資料夾不符：{source}')
        header, body = text.split('\n---\n', 1)
        definitions[skill] = (source, header, body)
    commands = {skill: command_text(skill, header) for skill, (_, header, _) in definitions.items()}
    invocation = (
        'Claude Code 使用 `/ds-frame` 等技能指令。'
        if host == 'claude' else
        '此入口供 Codex 與 OpenCode 共用；執行環境以當次工具為準。'
        'Codex 使用 `$ds-frame`；OpenCode 用原生 skill 工具載入 `ds-frame`，'
        '安裝本套件的 commands 後亦可使用 `/ds-frame`。'
    )
    preamble = (
        '技能內資源路徑相對於本次載入的 SKILL.md，研究、資料與成果路徑相對於目前分析專案。'
        '先讀 `resources/skills/_shared/session.md`。\n'
        '接手時閱讀專案的 `research/question.md`、`research/plan.md` 與 `research/handoff.md`；'
        '尚未初始化時使用 ds-init，尚未定義問題時先用 ds-frame。\n'
        f'{invocation}直接透過對話工作，將證據寫入本專案文件。'
    )
    results = {}
    for skill, (source, header, body) in definitions.items():
        base = Path(HOSTS[host][0]) / skill
        body = portable_text(body, source, root)
        body = body.replace('{{SESSION_START}}', preamble).replace('{{INVOKE}}', HOSTS[host][1])
        if '{{' in body or '}}' in body:
            raise ValueError(f'未解析的模板欄位：{source}')
        results[base / 'SKILL.md'] = (
            header + '\n---\n\n<!-- Generated by tools/render_skills.py; edit skills/ templates. -->\n\n'
            f'技能套件版本：{version()}\n\n' + body.lstrip('\n')
        )
        for resource in resources_for(skill, root):
            results[base / 'resources' / resource.relative_to(root)] = portable_text(
                resource.read_text(encoding='utf-8'), resource, root,
            )
        if skill == 'ds-init':
            for folder in ('scripts', 'assets'):
                for asset in sorted((source.parent / folder).rglob('*')):
                    if asset.is_file() and '__pycache__' not in asset.parts and asset.suffix != '.pyc':
                        results[base / asset.relative_to(source.parent)] = asset.read_text(encoding='utf-8')
            for name, command in commands.items():
                results[base / 'assets/commands' / f'{name}.md'] = command
        if host == 'opencode':
            results[Path('.opencode/commands') / f'{skill}.md'] = commands[skill]
    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--host', choices=(*HOSTS, 'all'), default='all')
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true', help='read-only drift check')
    mode.add_argument('--write', action='store_true', help='render only template-owned paths')
    parser.add_argument('--output-root', type=Path, default=ROOT)
    args = parser.parse_args()
    outputs = {}
    for host in HOSTS if args.host == 'all' else [args.host]:
        outputs.update(render(host))
    failed = []
    for relative, text in outputs.items():
        target = args.output_root / relative
        if args.check:
            if not target.is_file() or target.read_text(encoding='utf-8') != text:
                failed.append(str(relative))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding='utf-8')
    if failed:
        print('Skills missing or stale; run python3 tools/render_skills.py --write:\n' + '\n'.join(failed), file=sys.stderr)
        return 1
    print('Skills current' if args.check else 'Skills rendered')
    return 0


if __name__ == '__main__':
    sys.exit(main())
